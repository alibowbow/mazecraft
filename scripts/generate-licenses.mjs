/** The license file at the package root, or in dist/ (Pretendard keeps it there). */
function licenseText(directory) {
  for (const folder of ['', 'dist']) {
    const base = join(directory, folder)
    if (!existsSync(base)) continue
    const file = readdirSync(base)
      .filter((name) => /^(licen[cs]e|copying)(\.|$)/i.test(name))
      .sort((a, b) => a.length - b.length)[0]
    if (file) return readFileSync(join(base, file), 'utf8').trim()
  }
  return null
}

/** A copyright and license notice at the top of the package's main file (clipper-lib). */
function headerNotice(directory, meta) {
  const entry = join(directory, meta.main ?? 'index.js')
  const main = [entry, `${entry}.js`].find((file) => existsSync(file) && !file.endsWith('/'))
  if (!main) return null
  const match = /^\s*\/\*[\s\S]*?\*\//.exec(readFileSync(main, 'utf8'))
  return match && /licen[cs]e/i.test(match[0]) ? match[0].trim() : null
}

const sections = [...packages]
  .filter((directory) => existsSync(join(directory, 'package.json')))
  .map((directory) => {
    const meta = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'))
    const license = typeof meta.license === 'string' ? meta.license : meta.license?.type ?? 'UNKNOWN'
    const notice = licenseText(directory) ?? headerNotice(directory, meta)
    const boost = /^BSL/i.test(license) && !notice?.includes('Permission is hereby granted') ? `\n\n${BOOST_LICENSE}` : ''
    const text = notice ? `${notice}${boost}` : `License: ${license}${boost}`
    const homepage = meta.homepage ?? (typeof meta.repository === 'string' ? meta.repository : meta.repository?.url) ?? ''
    return { name: meta.name, version: meta.version, license, homepage, text }
  })
  .sort((a, b) => a.name.localeCompare(b.name))

const rule = '='.repeat(72)
const output = [
  'MazeCraft · third-party notices',
  'Packages included in the production build and their licenses.',
  'Generated by scripts/generate-licenses.mjs; do not edit by hand.',
  '',
  ...sections.flatMap(({ name, version, license, homepage, text }) => [
    rule,
    `${name} ${version} (${license})`,
    ...(homepage ? [homepage.replace(/^git\+/, '')] : []),
    '-'.repeat(72),
    text,
    '',
  ]),
].join('\n')

writeFileSync(join(root, 'public', 'licenses.txt'), `${output}\n`)
console.log(`public/licenses.txt: ${sections.length} packages`)
for (const { name, version, license } of sections) console.log(`  ${name}@${version} ${license}`)
