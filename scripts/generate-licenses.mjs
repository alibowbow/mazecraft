// Writes public/licenses.txt: the license of every third-party package that
// ends up in the production bundle (app and workers). Run after changing
// dependencies: npm run licenses
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'vite'

const root = fileURLToPath(new URL('..', import.meta.url))
const packages = new Set()

function packageRoot(id) {
  const path = id.replace(/^\0/, '').split('?')[0]
  const marker = path.lastIndexOf('/node_modules/')
  if (marker < 0) return null
  const rest = path.slice(marker + '/node_modules/'.length).split('/')
  const name = rest[0].startsWith('@') ? `${rest[0]}/${rest[1]}` : rest[0]
  return join(path.slice(0, marker), 'node_modules', name)
}

const collect = () => ({
  name: 'collect-bundled-packages',
  generateBundle(_options, bundle) {
    for (const output of Object.values(bundle)) {
      if (output.type !== 'chunk') continue
      for (const id of Object.keys(output.modules)) {
        const directory = packageRoot(id)
        if (directory) packages.add(directory)
      }
    }
  },
  // CSS imports (the Pretendard font) do not appear in chunk module lists.
  load(id) {
    const directory = packageRoot(id)
    if (directory && /\.(css|woff2?)$/.test(id.split('?')[0])) packages.add(directory)
    return null
  },
})

await build({
  root,
  logLevel: 'error',
  build: { write: false },
  plugins: [collect()],
  worker: { plugins: () => [collect()] },
})

